//! `vexor startup` / `vexor unstartup`: start the daemon at boot (PM2
//! `startup`).
//!
//! The daemon restores every app from its own state when it starts, so the
//! service only has to run `vexor daemon`. Stopping the service stops only
//! the daemon, never the apps (they outlive it, docs/architecture.md §7).
//!
//! - Linux: a systemd system unit `vexor-<user>.service`, running as that
//!   user. Installing needs root; without it, the exact `sudo` command is
//!   printed instead (Vexor never elevates by itself).
//! - macOS: a per-user LaunchAgent `dev.vexor.daemon.<user>.plist`; no
//!   root needed.

use std::path::{Path, PathBuf};
use std::process::Command;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Init {
    Systemd,
    Launchd,
}

impl Init {
    pub fn parse(s: &str) -> Result<Init, String> {
        match s {
            "systemd" => Ok(Init::Systemd),
            "launchd" => Ok(Init::Launchd),
            other => Err(format!(
                "unsupported init system {other:?}; supported: systemd, launchd"
            )),
        }
    }

    pub fn detect() -> Result<Init, String> {
        if cfg!(target_os = "macos") {
            return Ok(Init::Launchd);
        }
        if Path::new("/run/systemd/system").exists() {
            return Ok(Init::Systemd);
        }
        Err("could not detect systemd (no /run/systemd/system); OpenRC, upstart and SysV init are not supported yet".into())
    }
}

/// Everything needed to write the service file.
#[derive(Debug, Clone)]
pub struct Target {
    pub user: String,
    pub home: PathBuf,
    pub exe: PathBuf,
    /// The user's home directory (for the LaunchAgents folder).
    pub user_home: PathBuf,
}

pub fn systemd_name(user: &str) -> String {
    format!("vexor-{user}.service")
}

pub fn systemd_path(user: &str) -> PathBuf {
    PathBuf::from("/etc/systemd/system").join(systemd_name(user))
}

pub fn launchd_label(user: &str) -> String {
    format!("dev.vexor.daemon.{user}")
}

pub fn launchd_path(t: &Target) -> PathBuf {
    t.user_home
        .join("Library/LaunchAgents")
        .join(format!("{}.plist", launchd_label(&t.user)))
}

/// Quote a value for a systemd unit (ExecStart words, Environment values).
fn systemd_quote(s: &str) -> String {
    let escaped = s.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

pub fn systemd_unit(t: &Target) -> String {
    format!(
        "# Generated by `vexor startup`. Remove with `vexor unstartup`.\n\
         [Unit]\n\
         Description=Vexor process manager ({user})\n\
         Documentation=https://github.com/gauravgitgithub/vexor\n\
         After=network-online.target\n\
         Wants=network-online.target\n\
         \n\
         [Service]\n\
         Type=simple\n\
         User={user}\n\
         Environment={env}\n\
         ExecStart={exe} --home {home} daemon\n\
         Restart=on-failure\n\
         RestartSec=2\n\
         # Stopping or restarting the service stops only the daemon; apps keep\n\
         # running and the next daemon reconnects to them.\n\
         KillMode=process\n\
         LimitNOFILE=1048576\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n",
        user = t.user,
        env = systemd_quote(&format!("VEXOR_HOME={}", t.home.display())),
        exe = systemd_quote(&t.exe.to_string_lossy()),
        home = systemd_quote(&t.home.to_string_lossy()),
    )
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

pub fn launchd_plist(t: &Target) -> String {
    let arg = |s: &str| format!("    <string>{}</string>\n", xml_escape(s));
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n\
         <!-- Generated by `vexor startup`. Remove with `vexor unstartup`. -->\n\
         <plist version=\"1.0\">\n\
         <dict>\n\
         \x20 <key>Label</key>\n\
         \x20 <string>{label}</string>\n\
         \x20 <key>ProgramArguments</key>\n\
         \x20 <array>\n\
         {a0}{a1}{a2}{a3}\
         \x20 </array>\n\
         \x20 <key>EnvironmentVariables</key>\n\
         \x20 <dict>\n\
         \x20   <key>VEXOR_HOME</key>\n\
         \x20   <string>{home}</string>\n\
         \x20 </dict>\n\
         \x20 <key>RunAtLoad</key>\n\
         \x20 <true/>\n\
         \x20 <key>KeepAlive</key>\n\
         \x20 <dict>\n\
         \x20   <key>SuccessfulExit</key>\n\
         \x20   <false/>\n\
         \x20 </dict>\n\
         \x20 <!-- Apps outlive the daemon: launchd must not kill them with it. -->\n\
         \x20 <key>AbandonProcessGroup</key>\n\
         \x20 <true/>\n\
         \x20 <key>StandardErrorPath</key>\n\
         \x20 <string>{err}</string>\n\
         </dict>\n\
         </plist>\n",
        label = xml_escape(&launchd_label(&t.user)),
        a0 = arg(&t.exe.to_string_lossy()),
        a1 = arg("--home"),
        a2 = arg(&t.home.to_string_lossy()),
        a3 = arg("daemon"),
        home = xml_escape(&t.home.to_string_lossy()),
        err = xml_escape(&t.home.join("daemon.err").to_string_lossy()),
    )
}

fn is_root() -> bool {
    rustix::process::geteuid().is_root()
}

fn run(cmd: &mut Command) -> Result<(), String> {
    let shown = format!("{cmd:?}");
    let status = cmd
        .status()
        .map_err(|e| format!("cannot run {shown}: {e}"))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("{shown} failed ({status})"))
    }
}

/// The command line to re-run this as root, for systemd.
fn sudo_hint(t: &Target, sub: &str) -> String {
    format!(
        "sudo {} --home {} {sub} systemd --user {}",
        shell_quote(&t.exe.to_string_lossy()),
        shell_quote(&t.home.to_string_lossy()),
        t.user
    )
}

fn shell_quote(s: &str) -> String {
    if s.chars()
        .all(|c| c.is_ascii_alphanumeric() || "/._-".contains(c))
    {
        s.to_owned()
    } else {
        format!("'{}'", s.replace('\'', "'\\''"))
    }
}

pub fn install(init: Init, t: &Target, print_only: bool) -> Result<String, String> {
    match init {
        Init::Systemd => {
            let unit = systemd_unit(t);
            if print_only {
                return Ok(unit);
            }
            if !is_root() {
                return Err(format!(
                    "installing a systemd service needs root. Run:\n\n  {}\n\n(or `vexor startup --print` to see the unit first)",
                    sudo_hint(t, "startup")
                ));
            }
            let path = systemd_path(&t.user);
            vexor_shim::write_atomic(&path, unit.as_bytes())
                .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
            set_mode(&path, 0o644)?;
            run(Command::new("systemctl").arg("daemon-reload"))?;
            run(Command::new("systemctl")
                .args(["enable", "--now"])
                .arg(systemd_name(&t.user)))?;
            Ok(format!(
                "installed and started {}; apps in {} start at boot",
                path.display(),
                t.home.display()
            ))
        }
        Init::Launchd => {
            let plist = launchd_plist(t);
            if print_only {
                return Ok(plist);
            }
            let path = launchd_path(t);
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
            }
            vexor_shim::write_atomic(&path, plist.as_bytes())
                .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
            set_mode(&path, 0o644)?;
            let domain = format!("gui/{}", rustix::process::getuid().as_raw());
            // Replace an older registration, if any.
            let _ = Command::new("launchctl")
                .args(["bootout", &domain])
                .arg(&path)
                .stderr(std::process::Stdio::null())
                .status();
            run(Command::new("launchctl")
                .args(["bootstrap", &domain])
                .arg(&path))?;
            Ok(format!(
                "installed {}; the daemon starts at login",
                path.display()
            ))
        }
    }
}

pub fn uninstall(init: Init, t: &Target) -> Result<String, String> {
    match init {
        Init::Systemd => {
            if !is_root() {
                return Err(format!(
                    "removing a systemd service needs root. Run:\n\n  {}",
                    sudo_hint(t, "unstartup")
                ));
            }
            let name = systemd_name(&t.user);
            // `disable --now` stops only the daemon (KillMode=process).
            let _ = run(Command::new("systemctl").args(["disable", "--now", &name]));
            let path = systemd_path(&t.user);
            match std::fs::remove_file(&path) {
                Ok(()) => {}
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                    return Ok(format!("{} was not installed", path.display()));
                }
                Err(e) => return Err(format!("cannot remove {}: {e}", path.display())),
            }
            run(Command::new("systemctl").arg("daemon-reload"))?;
            Ok(format!(
                "removed {}; running apps were not stopped",
                path.display()
            ))
        }
        Init::Launchd => {
            let path = launchd_path(t);
            if !path.exists() {
                return Ok(format!("{} was not installed", path.display()));
            }
            let domain = format!("gui/{}", rustix::process::getuid().as_raw());
            let _ = Command::new("launchctl")
                .args(["bootout", &domain])
                .arg(&path)
                .status();
            std::fs::remove_file(&path)
                .map_err(|e| format!("cannot remove {}: {e}", path.display()))?;
            Ok(format!(
                "removed {}; running apps were not stopped",
                path.display()
            ))
        }
    }
}

fn set_mode(path: &Path, mode: u32) -> Result<(), String> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(mode))
        .map_err(|e| format!("cannot set permissions on {}: {e}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn target() -> Target {
        Target {
            user: "deploy".into(),
            home: PathBuf::from("/home/deploy/.vexor"),
            exe: PathBuf::from("/opt/vexor 1/bin/vexor"),
            user_home: PathBuf::from("/home/deploy"),
        }
    }

    #[test]
    fn systemd_unit_runs_the_daemon_as_the_user_and_keeps_apps() {
        let u = systemd_unit(&target());
        assert!(u.contains("User=deploy\n"));
        assert!(u.contains(
            "ExecStart=\"/opt/vexor 1/bin/vexor\" --home \"/home/deploy/.vexor\" daemon\n"
        ));
        assert!(u.contains("Environment=\"VEXOR_HOME=/home/deploy/.vexor\"\n"));
        assert!(
            u.contains("KillMode=process\n"),
            "stopping the service must not kill apps"
        );
        assert!(u.contains("Restart=on-failure\n"));
        assert!(u.contains("WantedBy=multi-user.target\n"));
        assert_eq!(
            systemd_path("deploy"),
            PathBuf::from("/etc/systemd/system/vexor-deploy.service")
        );
    }

    #[test]
    fn systemd_quoting() {
        assert_eq!(systemd_quote(r#"a "b" \c"#), r#""a \"b\" \\c""#);
    }

    #[test]
    fn launchd_plist_escapes_and_keeps_apps() {
        let mut t = target();
        t.home = PathBuf::from("/Users/a&b/.vexor");
        let p = launchd_plist(&t);
        assert!(p.contains("<string>dev.vexor.daemon.deploy</string>"));
        assert!(p.contains("<string>/opt/vexor 1/bin/vexor</string>"));
        assert!(p.contains("<string>/Users/a&amp;b/.vexor</string>"));
        assert!(!p.contains("a&b"), "unescaped &");
        assert!(p.contains("<key>AbandonProcessGroup</key>\n  <true/>"));
        assert!(p.contains("<key>RunAtLoad</key>\n  <true/>"));
        assert_eq!(
            launchd_path(&t),
            PathBuf::from("/home/deploy/Library/LaunchAgents/dev.vexor.daemon.deploy.plist")
        );
    }

    #[test]
    fn plist_is_valid_on_macos() {
        if !cfg!(target_os = "macos") {
            return;
        }
        let dir = tempfile::tempdir().expect("tempdir");
        let path = dir.path().join("t.plist");
        std::fs::write(&path, launchd_plist(&target())).expect("write");
        let out = Command::new("plutil")
            .arg("-lint")
            .arg(&path)
            .output()
            .expect("plutil");
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stdout)
        );
    }

    #[test]
    fn sudo_hint_quotes_paths() {
        let h = sudo_hint(&target(), "startup");
        assert_eq!(
            h,
            "sudo '/opt/vexor 1/bin/vexor' --home /home/deploy/.vexor startup systemd --user deploy"
        );
    }

    #[test]
    fn init_names() {
        assert_eq!(Init::parse("systemd"), Ok(Init::Systemd));
        assert!(Init::parse("openrc").is_err());
    }
}
